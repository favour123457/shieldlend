/**
 * Build an Anchor Program instance using the connected wallet.
 *
 * @param {object} wallet - wallet adapter wallet object
 * @returns {{ program, provider, connection }}
 */
export function getProgram(wallet) {
  const connection = new Connection(RPC_URL, "confirmed");
  const provider = new AnchorProvider(connection, wallet, {
    commitment: "confirmed",
    preflightCommitment: "confirmed",
  });
  const program = new Program(idl, provider);
  console.log("[ShieldLend] Anchor program connected", {
    programId: PROGRAM_ID,
    rpcUrl: RPC_URL,
    wallet: wallet.publicKey?.toBase58?.(),
  });
  return { program, provider, connection };
}

