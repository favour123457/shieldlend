/**
 * Derive the position PDA for a user.
 *
 * Seeds: ["position", userPubkey]
 *
 * @param {string|PublicKey} programId
 * @param {string|PublicKey} userPubkey
 * @returns {PublicKey}
 */
export function getPositionAddress(programId, userPubkey) {
  const [pda] = PublicKey.findProgramAddressSync(
    [Buffer.from("position"), new PublicKey(userPubkey).toBuffer()],
    new PublicKey(programId)
  );
  return pda;
}

