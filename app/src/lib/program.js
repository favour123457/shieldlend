/**
 * Derive all Arcium-required account addresses for a computation.
 *
 * @param {string|PublicKey} programId
 * @param {bigint|BN|number} computationOffset
 * @returns {object} Named account addresses
 */
export function getArciumAccounts(programId, computationOffset) {
  const offsetBN =
    computationOffset instanceof BN
      ? computationOffset
      : new BN(computationOffset.toString());

  const programPubkey = new PublicKey(programId);

  const [signPdaAccount] = PublicKey.findProgramAddressSync(
    [Buffer.from("ArciumSignerAccount")],
    programPubkey
  );

  const accounts = {
    computationAccount: getComputationAccAddress(CLUSTER_OFFSET, offsetBN),
    clusterAccount: getClusterAccAddress(CLUSTER_OFFSET),
    mxeAccount: getMXEAccAddress(programPubkey),
    mempoolAccount: getMempoolAccAddress(CLUSTER_OFFSET),
    executingPool: getExecutingPoolAccAddress(CLUSTER_OFFSET),
    poolAccount: getFeePoolAccAddress(),
    clockAccount: getClockAccAddress(),
    signPdaAccount,
    arciumProgram: getArciumProgramId(),
  };

  console.log("[ShieldLend] Derived Arcium accounts", {
    computationOffset: offsetBN.toString(),
    signPdaAccount: accounts.signPdaAccount.toBase58(),
    computationAccount: accounts.computationAccount.toBase58(),
    clusterAccount: accounts.clusterAccount.toBase58(),
    mxeAccount: accounts.mxeAccount.toBase58(),
    mempoolAccount: accounts.mempoolAccount.toBase58(),
    executingPool: accounts.executingPool.toBase58(),
    poolAccount: accounts.poolAccount.toBase58(),
    clockAccount: accounts.clockAccount.toBase58(),
    arciumProgram: accounts.arciumProgram.toBase58(),
  });

  return accounts;
}

/**
 * Derive the comp_def PDA for a given circuit name.
 *
 * @param {string|PublicKey} programId
 * @param {string} circuitName - e.g. "check_liquidatable"
 * @returns {PublicKey}
 */
export function getCompDefAddress(programId, circuitName) {
  const offsetBytes = getCompDefAccOffset(circuitName);
  const offset = Buffer.from(offsetBytes).readUInt32LE(0);
  const address = getCompDefAccAddress(new PublicKey(programId), offset);
  console.log("[ShieldLend] Derived computation definition", {
    circuitName,
    offsetBytes: Array.from(offsetBytes),
    offset,
    compDefAccount: address.toBase58(),
  });
  return address;
}

